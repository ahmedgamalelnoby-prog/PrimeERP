class SallaOrder(Base):
    __tablename__ = "salla_orders"

    id = Column(Integer, primary_key=True)
    company_id = Column(Integer, ForeignKey("companies.id", ondelete="CASCADE"), nullable=False, index=True)
    connection_id = Column(Integer, ForeignKey("integration_connections.id", ondelete="CASCADE"), nullable=False, index=True)
    external_id = Column(String(160), nullable=False)
    reference_id = Column(String(160), index=True)
    status = Column(String(80))
    payment_status = Column(String(80))
    fulfillment_status = Column(String(80))
    order_type = Column(String(80))
    currency = Column(String(20))
    exchange_rate = Column(Numeric(20, 8))
    subtotal = Column(Numeric(20, 4))
    discount = Column(Numeric(20, 4))
    shipping = Column(Numeric(20, 4))
    tax = Column(Numeric(20, 4))
    total = Column(Numeric(20, 4))
    cod_amount = Column(Numeric(20, 4))
    customer_id = Column(String(160), index=True)
    store_id = Column(String(160))
    created_at_salla = Column(DateTime(timezone=True))
    updated_at_salla = Column(DateTime(timezone=True))
    urls = Column(JSON, nullable=False, default=dict)
    payment_methods = Column(JSON, nullable=False, default=list)
    metadata_json = Column(JSON, nullable=False, default=dict)
    raw_payload = Column(JSON, nullable=False, default=dict)
    created_at = Column(DateTime, nullable=False, server_default=func.now())
    updated_at = Column(DateTime, nullable=False, server_default=func.now(), onupdate=func.now())

    __table_args__ = (UniqueConstraint("connection_id", "external_id", name="uq_salla_order_connection_external"),)


